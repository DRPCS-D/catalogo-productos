CREATE OR REPLACE FUNCTION public._web_restrict(p_data jsonb, p_sucs text[])
 RETURNS jsonb
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  with cols as (
    select cc.ord, cc.v as col,
      (select coalesce(jsonb_agg(s), '[]'::jsonb)
         from jsonb_array_elements(cc.v->'stock') s
        where lower(btrim(s->>'sucursal')) = any(p_sucs)) as stock_new,
      (select coalesce(jsonb_agg(jsonb_build_object(
                'talle', t.v->'talle',
                'totalStock', (select coalesce(sum((s->>'cantidad')::int), 0)
                                 from jsonb_array_elements(t.v->'stock') s
                                where lower(btrim(s->>'sucursal')) = any(p_sucs)),
                'stock', (select coalesce(jsonb_agg(s), '[]'::jsonb)
                            from jsonb_array_elements(t.v->'stock') s
                           where lower(btrim(s->>'sucursal')) = any(p_sucs))
              ) order by t.ord), '[]'::jsonb)
         from jsonb_array_elements(cc.v->'talles') with ordinality as t(v, ord)) as talles_new
    from jsonb_array_elements(p_data->'colores') with ordinality as cc(v, ord)
  ), cq as (
    select cols.*, (select coalesce(sum((s->>'cantidad')::int), 0) from jsonb_array_elements(cols.stock_new) s) as q
    from cols
  )
  select p_data || jsonb_build_object(
    'colores', coalesce((select jsonb_agg(col || jsonb_build_object('stock', stock_new, 'talles', talles_new, 'totalStock', q) order by ord)
                           from cq where q > 0), '[]'::jsonb),
    'totalStock', coalesce((select sum(q) from cq), 0));
$function$;

CREATE OR REPLACE FUNCTION public.verify_admin_pin(pin text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare stored_hash text;
begin
  if pin is null or length(pin) = 0 then return false; end if;
  select pin_hash into stored_hash from public.admin_secret where id = 1;
  if stored_hash is null then return false; end if;
  return extensions.crypt(pin, stored_hash) = stored_hash;
end; $function$;

CREATE OR REPLACE FUNCTION public.verify_access_password(pw text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
  select exists (select 1 from public.access_secret where id = 1 and pw_hash = crypt(pw, pw_hash));
$function$;

CREATE OR REPLACE FUNCTION public.catalog_mode_pw_ok_(p_mode text, pw text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
  select case
    when p_mode in ('general', 'mayorista', 'minorista') then
      exists (select 1 from public.access_secret where id = 1 and pw_hash = crypt(pw, pw_hash))
    when p_mode = 'mayorista1' then
      exists (select 1 from public.access_secret_mode where mode = 'mayorista1' and pw_hash = crypt(pw, pw_hash))
    else false
  end;
$function$;

CREATE OR REPLACE FUNCTION public.verify_access_password_mode(p_mode text, pw text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
  select public.catalog_mode_pw_ok_(p_mode, pw);
$function$;

CREATE OR REPLACE FUNCTION public.admin_catalog_meta(pin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
begin
  if not public.verify_admin_pin(pin) then
    raise exception 'PIN invalido' using errcode = '28000';
  end if;
  return jsonb_build_object(
    'marcas',     (select coalesce(jsonb_agg(m order by m), '[]'::jsonb)
                     from (select distinct marca m from public.products where marca is not null) x),
    'sucursales', (select coalesce(jsonb_agg(s order by s), '[]'::jsonb)
                     from (select distinct sucursal s from public.product_stock where sucursal is not null) y)
  );
end; $function$;

CREATE OR REPLACE FUNCTION public.get_catalog_mode(p_mode text, pw text)
 RETURNS TABLE(data jsonb, updated_at timestamp with time zone)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
begin

  mode text not null primary key,
  title text not null,
  price_mode text,
  sucursales jsonb not null default '[]'::jsonb,
  marcas_excluidas jsonb not null default '[]'::jsonb,
  promo_visible boolean not null default true,
  locked boolean not null default false,
  restrict_modal_sucursales boolean not null default false,
  updated_at timestamptz not null default now()
);

-- Tablas normalizadas (las reescribe sync.py cada hora; las usa buscar_productos_retail)
create table public.products (
  cod_fabrica text not null primary key,
  id bigint,
  nm_produto text,
  marca text,
  grupo text,
  subgrupo text,
  colecao text,
  precio_minorista numeric,
  precio_minorista_promo numeric,
  precio_minorista_promo_inicio date,
  precio_minorista_promo_validade date,
  precio_mayorista numeric,
  precio_mayorista_promo numeric,
  precio_mayorista_promo_inicio date,
  precio_mayorista_promo_validade date,
  q_mas_vendio integer,
  total_stock integer,
  updated_at timestamptz default now(),
  precio_mayorista1 numeric,
  precio_mayorista1_promo numeric,
  precio_mayorista1_promo_inicio date,
  precio_mayorista1_promo_validade date

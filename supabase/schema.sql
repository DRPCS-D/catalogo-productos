CREATE OR REPLACE FUNCTION public.save_page_config(pin text, p_mode text, p_config jsonb)
 RETURNS page_config
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare result public.page_config;
begin
  if not public.verify_admin_pin(pin) then
    raise exception 'PIN invalido' using errcode = '28000';
  end if;
  if p_mode not in ('general', 'mayorista', 'minorista', 'mayorista1') then
    raise exception 'mode invalido: % (debe ser general | mayorista | minorista | mayorista1)', p_mode using errcode = '22023';
  end if;
  insert into public.page_config as pc (
    mode, title, price_mode, sucursales, marcas_excluidas,
    promo_visible, locked, restrict_modal_sucursales, updated_at
  ) values (
    p_mode,
    coalesce(p_config->>'title', 'Catálogo'),
    nullif(p_config->>'priceMode', ''),
    coalesce(p_config->'sucursales', '[]'::jsonb),
    coalesce(p_config->'marcasExcluidas', '[]'::jsonb),
    coalesce((p_config->>'promoVisible')::boolean, true),
    coalesce((p_config->>'locked')::boolean, false),
    coalesce((p_config->>'restrictModalSucursales')::boolean, false),
    now()
  )
  on conflict (mode) do update set
    title = excluded.title, price_mode = excluded.price_mode,
    sucursales = excluded.sucursales, marcas_excluidas = excluded.marcas_excluidas,
    promo_visible = excluded.promo_visible, locked = excluded.locked,
    restrict_modal_sucursales = excluded.restrict_modal_sucursales, updated_at = now()
  returning * into result;
  return result;
end; $function$;

CREATE OR REPLACE FUNCTION public.buscar_productos_retail(p_marca text[] DEFAULT NULL::text[], p_talle text[] DEFAULT NULL::text[], p_categoria text[] DEFAULT NULL::text[], p_grupo text[] DEFAULT NULL::text[], p_sucursal text[] DEFAULT NULL::text[], p_temporada text[] DEFAULT NULL::text[], p_color text[] DEFAULT NULL::text[])
 RETURNS TABLE(cod_fabrica text, marca text, nm_produto text, subgrupo text, grupo text, colecao text, color text, img_id text, talle text, precio_activo numeric, precio_regular numeric, es_promo boolean, sucursal text, stock integer)
 LANGUAGE sql
 STABLE
AS $function$
  with cfg as (
    select sucursales, marcas_excluidas from page_config where mode = 'minorista'
  )
  select
    p.cod_fabrica, p.marca, p.nm_produto, p.subgrupo, p.grupo, p.colecao,
    c.color, c.img_id, g.grade,
    case when p.precio_minorista_promo > 0
          and p.precio_minorista_promo_inicio <= current_date
          and current_date <= p.precio_minorista_promo_validade
     then p.precio_minorista_promo else p.precio_minorista end,
    p.precio_minorista,
    (p.precio_minorista_promo > 0
      and p.precio_minorista_promo_inicio <= current_date
      and current_date <= p.precio_minorista_promo_validade),
    s.sucursal, s.cantidad
  from products p
  join product_colors c on c.cod_fabrica = p.cod_fabrica
  join product_grades g on g.cod_fabrica = c.cod_fabrica and g.color = c.color
  join product_stock  s on s.cod_fabrica = g.cod_fabrica and s.color = g.color and s.grade = g.grade
  cross join cfg
  where s.cantidad > 0
    and cfg.sucursales ? s.sucursal
    and not (cfg.marcas_excluidas ? p.marca)
    and (p_marca     is null or exists (
           select 1 from unnest(p_marca) rm
           where regexp_replace(upper(p.marca), '[^A-Z0-9]', '', 'g') = regexp_replace(upper(rm), '[^A-Z0-9]', '', 'g')
         ))
    and (p_talle     is null or g.grade    = any(p_talle))
    and (p_categoria is null or btrim(p.subgrupo) = any(p_categoria))
    and (p_grupo     is null or p.grupo    = any(p_grupo))
    and (p_sucursal  is null or s.sucursal = any(p_sucursal))
    and (p_temporada is null or p.colecao  = any(p_temporada))
    and (p_color     is null or exists (
           select 1 from unnest(p_color) rc
           where c.color ilike rc || '%'
         ))
  order by p.marca, p.nm_produto
  limit 200
$function$;


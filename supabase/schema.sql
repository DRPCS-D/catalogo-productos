create table public.product_grades (
  cod_fabrica text not null,
  color text not null,
  grade text not null,
  ean text,
  total_stock integer,
  primary key (cod_fabrica, color, grade),
  foreign key (cod_fabrica, color) references public.product_colors(cod_fabrica, color) on delete cascade

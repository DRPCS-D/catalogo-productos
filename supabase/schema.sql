create table public.product_stock (
  cod_fabrica text not null,
  color text not null,
  grade text not null,
  sucursal text not null,
  cantidad integer not null default 0,
  data_ult_cmp date,
  data_ult_vnd date,
  primary key (cod_fabrica, color, grade, sucursal),
  foreign key (cod_fabrica, color, grade) references public.product_grades(cod_fabrica, color, grade) on delete cascade
);


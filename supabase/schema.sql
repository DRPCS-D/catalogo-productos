CREATE OR REPLACE FUNCTION public.get_products_page(p_page integer DEFAULT 1, p_size integer DEFAULT 24, p_search text DEFAULT NULL::text, p_marca text DEFAULT NULL::text, p_grupo text DEFAULT NULL::text, p_sucursal text DEFAULT NULL::text, p_sucursales text[] DEFAULT NULL::text[], p_excluir_subgrupos text[] DEFAULT NULL::text[])
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
  v_page int := greatest(coalesce(p_page,1),1);
  v_size int := least(greatest(coalesce(p_size,24),1),100);
  v_q text := unaccent(lower(trim(coalesce(p_search,''))));
  v_terms text[] := array(select t from unnest(string_to_array(v_q,' ')) t where t <> '');
  v_sucs text[] := array(
    select distinct lower(btrim(x))
    from unnest(coalesce(p_sucursales, '{}'::text[]) || array[coalesce(p_sucursal,'')]) x
    where btrim(x) <> '');
  v_exc text[] := array(
    select distinct lower(btrim(x)) from unnest(coalesce(p_excluir_subgrupos, '{}'::text[])) x where btrim(x) <> '');
  v_total int; v_items jsonb; v_upd timestamptz;
begin
  select count(*), max(updated_at) into v_total, v_upd
  from public.web_catalog w
  where (p_marca is null or p_marca = '' or lower(btrim(w.marca)) = lower(btrim(p_marca)))
    and (p_grupo is null or p_grupo = '' or lower(btrim(w.grupo)) = lower(btrim(p_grupo)))
    and (cardinality(v_sucs) = 0 or exists (select 1 from unnest(w.sucursales) x where lower(btrim(x)) = any(v_sucs)))
    and (cardinality(v_exc) = 0 or w.subgrupo is null or lower(btrim(w.subgrupo)) <> all(v_exc))
    and not exists (select 1 from unnest(v_terms) t where position(t in w.search) = 0);

  select coalesce(jsonb_agg(case when cardinality(v_sucs) > 0 then public._web_restrict(x.data, v_sucs) else x.data end order by x.rn), '[]'::jsonb)
    into v_items
  from (
    select w.data, row_number() over (order by w.q_mas_vendio desc nulls last, w.nm_produto, w.cod_fabrica) rn
    from public.web_catalog w
    where (p_marca is null or p_marca = '' or lower(btrim(w.marca)) = lower(btrim(p_marca)))
      and (p_grupo is null or p_grupo = '' or lower(btrim(w.grupo)) = lower(btrim(p_grupo)))
      and (cardinality(v_sucs) = 0 or exists (select 1 from unnest(w.sucursales) x where lower(btrim(x)) = any(v_sucs)))
      and (cardinality(v_exc) = 0 or w.subgrupo is null or lower(btrim(w.subgrupo)) <> all(v_exc))
      and not exists (select 1 from unnest(v_terms) t where position(t in w.search) = 0)
    order by w.q_mas_vendio desc nulls last, w.nm_produto, w.cod_fabrica
    limit v_size offset (v_page-1)*v_size
  ) x;

  return jsonb_build_object('page', v_page, 'size', v_size, 'total', v_total,
    'total_pages', greatest(ceil(v_total::numeric / v_size)::int, 1),
    'updated_at', v_upd, 'items', v_items);
end $function$;

CREATE OR REPLACE FUNCTION public.refresh_web_catalog(p_data jsonb, p_updated timestamp with time zone)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
begin
  with src as materialized (
    select distinct on (e->>'codFabrica')
      e->>'codFabrica' as cod_fabrica,
      e->>'nmProduto'  as nm_produto,
      e->>'marca'      as marca,
      e->>'grupo'      as grupo,
      nullif(e->>'qMasVendio','')::numeric::integer as q_mas_vendio,
      unaccent(lower(coalesce(e->>'nmProduto','') || ' ' || coalesce(e->>'codFabrica','') || ' ' || coalesce(e->>'marca',''))) as search,
      array(
        select distinct st->>'sucursal'
        from jsonb_array_elements(coalesce(e->'colorsArr','[]'::jsonb)) c,
             jsonb_array_elements(coalesce(c->'gradesArr','[]'::jsonb)) g,
             jsonb_array_elements(coalesce(g->'stock','[]'::jsonb)) st
        where coalesce(nullif(st->>'cantidad','')::numeric,0) > 0 and st->>'sucursal' is not null
      ) as sucursales,
      jsonb_build_object(
        'id', e->'id',
        'codFabrica', e->'codFabrica',
        'nmProduto', e->'nmProduto',
        'marca', e->'marca',
        'grupo', e->'grupo',
        'subgrupo', e->'subgrupo',
        'colecao', e->'colecao',
        'precioMinorista', e->'precioMinorista',
        'precioMinoristaPromo', e->'precioMinoristaPromo',
        'precioMinoristaPromoInicio', e->'precioMinoristaPromoInicio',
        'precioMinoristaPromoValidade', e->'precioMinoristaPromoValidade',
        'totalStock', e->'totalStock',
        'colores', coalesce((
          select jsonb_agg(jsonb_build_object(
                   'color', c->'color', 'imagen', c->'imagen', 'imgId', c->'imgId',
                   'imgV', c->'imgV', 'totalStock', c->'totalStock',
                   'stock', coalesce((
                      select jsonb_agg(jsonb_build_object('sucursal', s.suc, 'cantidad', s.q) order by s.suc)
                      from (
                        select st->>'sucursal' suc, sum(coalesce(nullif(st->>'cantidad','')::numeric,0))::int q
                        from jsonb_array_elements(coalesce(c->'gradesArr','[]'::jsonb)) g,
                             jsonb_array_elements(coalesce(g->'stock','[]'::jsonb)) st
                        group by 1
                        having sum(coalesce(nullif(st->>'cantidad','')::numeric,0)) > 0
                      ) s
                   ), '[]'::jsonb),
                   'talles', coalesce((
                      select jsonb_agg(jsonb_build_object(
                               'talle', g.v->'grade',
                               'totalStock', g.v->'totalStock',
                               'stock', coalesce((
                                  select jsonb_agg(jsonb_build_object('sucursal', st->>'sucursal', 'cantidad', st->'cantidad'))
                                  from jsonb_array_elements(coalesce(g.v->'stock','[]'::jsonb)) st
                                  where coalesce(nullif(st->>'cantidad','')::numeric,0) > 0
                               ), '[]'::jsonb)
                             ) order by g.ord)
                      from jsonb_array_elements(coalesce(c->'gradesArr','[]'::jsonb)) with ordinality as g(v, ord)
                   ), '[]'::jsonb)))
          from jsonb_array_elements(coalesce(e->'colorsArr','[]'::jsonb)) c
        ), '[]'::jsonb)
      ) as data
    from jsonb_array_elements(p_data) e
    where e->>'codFabrica' is not null
    order by e->>'codFabrica'
  ),
  upserted as (
    insert into public.web_catalog as w
      (cod_fabrica, nm_produto, marca, grupo, q_mas_vendio, search, sucursales, data, updated_at)
    select cod_fabrica, nm_produto, marca, grupo, q_mas_vendio, search, sucursales, data, p_updated
    from src
    on conflict (cod_fabrica) do update
      set nm_produto = excluded.nm_produto, marca = excluded.marca, grupo = excluded.grupo,
          q_mas_vendio = excluded.q_mas_vendio, search = excluded.search,
          sucursales = excluded.sucursales, data = excluded.data, updated_at = excluded.updated_at
      where (w.data, w.sucursales, w.search, w.q_mas_vendio, w.nm_produto, w.marca, w.grupo)
            is distinct from
            (excluded.data, excluded.sucursales, excluded.search, excluded.q_mas_vendio,
             excluded.nm_produto, excluded.marca, excluded.grupo)
    returning 1
  )
  delete from public.web_catalog w
  where not exists (select 1 from src s where s.cod_fabrica = w.cod_fabrica);
end $function$;

CREATE OR REPLACE FUNCTION public.trg_refresh_web_catalog()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
begin
  perform public.refresh_web_catalog(new.data, new.updated_at);
  return null;
end $function$;

-- ---------- Trigger ----------
CREATE TRIGGER web_catalog_refresh AFTER INSERT OR UPDATE ON public.catalog_mode_cache
  FOR EACH ROW WHEN ((new.mode = 'minorista'::text)) EXECUTE FUNCTION trg_refresh_web_catalog();

